// Generates src/lib/image-data.ts with intrinsic dimensions + tiny blur placeholders.
// Run: node scripts/gen-image-data.mjs
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const dir = path.join(process.cwd(), "public", "images", "real");
const outFile = path.join(process.cwd(), "src", "lib", "image-data.ts");

const files = fs.readdirSync(dir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();

const entries = [];
for (const file of files) {
  const name = file.replace(/\.(jpe?g|png|webp)$/i, "");
  const full = path.join(dir, file);
  const meta = await sharp(full).rotate().metadata();

  const blur = await sharp(full)
    .rotate()
    .resize({ width: 20, height: 20, fit: "inside" })
    .jpeg({ quality: 45, chromaSubsampling: "4:2:0" })
    .toBuffer();

  entries.push({
    name,
    ext: path.extname(file).toLowerCase(),
    width: meta.width,
    height: meta.height,
    blur: `data:image/jpeg;base64,${blur.toString("base64")}`,
  });
}

const body = entries
  .map(
    (e) =>
      `  "${e.name}": { width: ${e.width}, height: ${e.height}, ext: "${e.ext}", blurDataURL: "${e.blur}" },`,
  )
  .join("\n");

const content = `// AUTO-GENERATED by scripts/gen-image-data.mjs — do not edit by hand.
export interface ImageMeta {
  width: number;
  height: number;
  ext: string;
  blurDataURL: string;
}

export const IMAGES = {
${body}
} as const satisfies Record<string, ImageMeta>;

export type ImageKey = keyof typeof IMAGES;

export function imageSrc(key: ImageKey): string {
  return \`/images/real/\${key}\${IMAGES[key].ext}\`;
}
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, content, "utf8");

console.log(`Wrote ${entries.length} entries to ${path.relative(process.cwd(), outFile)}`);
for (const e of entries) console.log(`  ${e.name.padEnd(40)} ${e.width}x${e.height}`);
